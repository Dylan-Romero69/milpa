"""Pruebas de Milpa: programas con errores de escritura, de tipos, de ámbitos y de tamaño.
Cada caso: (nombre, programa, esperado) con esperado 'ok' (debe compilar) o 'error' (debe rechazarse
con un mensaje, nunca con una excepción de Python)."""

# Fase en la que debe fallar cada caso de error, según el grupo del nombre ('lex/', 'sin/', ...).
# Un programa con un error sintáctico no debe "colarse" hasta el análisis semántico, ni al revés.
PREFIJOS_POR_GRUPO = {
    "lex": ("E-LEX", "E-SIN"),       # algunos errores de escritura los detecta el parser
    "sin": ("E-SIN", "E-LEX"),
    "sem": ("E-SEM", "E-DOM"),
    "zon": ("E-SEM", "E-DOM"),
}
# Casos que por diseño pueden fallar en otra fase (con la razón).
EXCEPCIONES_DE_FASE = {
    "sem/repetir con condición entera": ("E-SIN",),   # 'repetir' no existe en el prototipo
}


def fases_validas(nombre):
    """Prefijos de código con los que puede rechazarse un caso; None si no se exige fase."""
    if nombre in EXCEPCIONES_DE_FASE:
        return EXCEPCIONES_DE_FASE[nombre]
    return PREFIJOS_POR_GRUPO.get(nombre.split("/")[0])


